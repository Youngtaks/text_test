package com.jjm.jjmoa.model;

public class JobCategoryDTO {
		private String jobcategory_idx;
		private String jobcategory_name;
		private String jobcategory_code;
		
		public String getJobcategory_idx() {
			return jobcategory_idx;
		}
		public void setJobcategory_idx(String jobcategory_idx) {
			this.jobcategory_idx = jobcategory_idx;
		}
		public String getJobcategory_name() {
			return jobcategory_name;
		}
		public void setJobcategory_name(String jobcategory_name) {
			this.jobcategory_name = jobcategory_name;
		}
		public String getJobcategory_code() {
			return jobcategory_code;
		}
		public void setJobcategory_code(String jobcategory_code) {
			this.jobcategory_code = jobcategory_code;
		}
		
}
